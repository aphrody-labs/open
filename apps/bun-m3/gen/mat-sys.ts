// Angular Material system colour tokens (--mat-sys-*) for the three contrast levels of the Theme Builder scheme,
// each as light-dark(light, dark) so the colour scheme of the page picks the mode. mat.theme() provides the
// rest of the system (typography, shape, elevation, state); these declarations pin the exact scheme roles.
// Output: theme/angular/mat-sys.css.  bun gen/mat-sys.ts
import { join } from "node:path";

const app = join(import.meta.dir, "..");
const theme = await Bun.file(join(app, "theme/theme.json")).json();
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const out = [`/* Generated by apps/bun-m3/gen/mat-sys.ts from theme/theme.json (source ${theme.source}). Do not edit. */`];
for (const [level, suffix] of [["standard", ""], ["medium", "-medium-contrast"], ["high", "-high-contrast"]] as const) {
  const light = theme.schemes[`light${suffix}`], dark = theme.schemes[`dark${suffix}`];
  const sel = level === "standard" ? `html, html[data-contrast="standard"]` : `html[data-contrast="${level}"]`;
  out.push(`${sel} {`, ...Object.keys(light).map((k) => `  --mat-sys-${kebab(k)}: light-dark(${light[k]}, ${dark[k]});`), "}");
}
await Bun.write(join(app, "theme/angular/mat-sys.css"), `${out.join("\n")}\n`);
console.log(`theme/angular/mat-sys.css: ${Object.keys(theme.schemes.light).length} roles x 3 contrast levels`);
